// baselineLints include the lint whose section the updater reads.
var baselineLints = []manifest.Lint{
	{Name: "check-coverage-drop", Language: "go", Speed: "quick", Description: "coverage"},
	{Name: "a", Language: "bash", Speed: "quick", Description: "first"},
}

const coverageConfig = "check-coverage-drop:\n" +
	"  reports:\n" +
	"    - format: go\n" +
	"      path: cov/go.out\n" +
	"    - format: cobertura\n" +
	"      path: cov/c.xml\n"

// coverageRepo is a git repository with a module and two coverage reports
// counting go a=3, go .=0 and cobertura lib=2 uncovered, and config as its
// config file.
func coverageRepo(t *testing.T, config string) string {
	t.Helper()
	repo := makeRepo(t)
	writeFile(t, filepath.Join(repo, "go.mod"), "module example.com/m\n")
	writeFile(t, filepath.Join(repo, "cov", "go.out"), "mode: set\n"+
		"example.com/m/a/x.go:3.1,5.2 3 0\n"+
		"example.com/m/main.go:1.1,2.2 1 1\n")
	writeFile(t, filepath.Join(repo, "cov", "c.xml"), `<coverage><sources><source>`+repo+`</source></sources>`+
		`<packages><package name="p"><classes><class filename="lib/t.sh"><lines>`+
		`<line number="1" hits="0"/><line number="2" hits="0"/><line number="3" hits="5"/>`+
		`</lines></class></classes></package></packages></coverage>`)
	if config != "" {
		writeFile(t, filepath.Join(repo, ".repo-toolbelt.yml"), config)
	}
	return repo
}

func runBaseline(t *testing.T, dir string, args ...string) result {
	t.Helper()
	var stdout, stderr bytes.Buffer
	runner := cli.Runner{Lints: baselineLints, Version: "1.2.3", Dir: dir}
	err := runner.Run(t.Context(), append([]string{"update-coverage-baseline"}, args...), func(string) string { return "" }, strings.NewReader(""), &stdout, &stderr)
	if err != nil {
		stderr.WriteString("error: " + err.Error() + "\n")
	}
	return result{code: cli.ExitCode(err), stdout: stdout.String(), stderr: stderr.String()}
}

const wantBaseline = "# Generated by toolbelt update-coverage-baseline. Do not edit.\n" +
	"cobertura lib 2\n" +
	"go . 0\n" +
	"go a 3\n"

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestRun_updateCoverageBaseline(t *testing.T) {
	t.Parallel()
	repo := coverageRepo(t, coverageConfig)
	writeFile(t, filepath.Join(repo, ".coverage-baseline.txt"), "go a 9\ngo gone 4\n")
	got := runBaseline(t, filepath.Join(repo, "src"))
	if got.code != 0 || got.stdout != "wrote .coverage-baseline.txt\n" || got.stderr != "" {
		t.Errorf("got %+v, want exit 0 naming the file written", got)
	}
	if content := readFile(t, filepath.Join(repo, ".coverage-baseline.txt")); content != wantBaseline {
		t.Errorf("baseline is\n%s\nwant\n%s", content, wantBaseline)
	}
	entries, err := os.ReadDir(repo)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if strings.Contains(e.Name(), ".tmp") {
			t.Errorf("a temporary file is left behind: %s", e.Name())
		}
	}
}

