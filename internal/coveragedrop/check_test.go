// history is a repository whose first commit holds a baseline of go a 4 and
// cobertura lib 3, above what the reports in its working tree count, so the
// tree check passes and only the history is judged.
type history struct {
	t    *testing.T
	root string
	base string
}

func newHistory(t *testing.T, first string) *history {
	t.Helper()
	h := &history{t: t, root: t.TempDir()}
	gitOut(t, h.root, "init", "--quiet", "--initial-branch=main")
	writeReports(t, h.root)
	writeFile(t, filepath.Join(h.root, ".gitignore"), "cov/\n")
	if first != "" {
		writeFile(t, filepath.Join(h.root, ".coverage-baseline.txt"), first)
	}
	h.commit("chore: start")
	h.base = h.head()
	return h
}

func (h *history) commit(message string) {
	h.t.Helper()
	gitOut(h.t, h.root, "add", "--all")
	gitOut(h.t, h.root, "-c", "user.name=Marker", "-c", "user.email=marker@example.invalid",
		"commit", "--quiet", "--allow-empty", "--message", message)
}

func (h *history) setBaseline(lines ...string) {
	h.t.Helper()
	writeFile(h.t, filepath.Join(h.root, ".coverage-baseline.txt"), baseline(lines...))
}

func (h *history) head() string {
	h.t.Helper()
	return gitOut(h.t, h.root, "rev-parse", "HEAD")
}

func (h *history) short(rev string) string {
	h.t.Helper()
	return gitOut(h.t, h.root, "rev-parse", "--short", rev)
}

func (h *history) check() ([]lintkit.Finding, error) {
	h.t.Helper()
	return check(h.t, h.root, section, h.base+"..HEAD")
}

var startBaseline = baseline("cobertura lib 3", "go a 4")

func raise(sha, format, unit string, from, to int, noReason bool) lintkit.Finding {
	msg := sha + " raises " + format + " " + unit + " " + strconv.Itoa(from) + " -> " + strconv.Itoa(to) +
		` uncovered without a "Coverage-Drop: ` + unit + ` - <reason>" trailer in its last paragraph`
	if noReason {
		msg += " (the trailer gives no reason)"
	}
	return lintkit.Finding{Path: ".coverage-baseline.txt", Message: msg}
}

func TestCheck_history(t *testing.T) {
	t.Parallel()
	const trailerA = "Coverage-Drop: a - the retry path it covered was removed, " + reasonSentinel
	tests := []struct {
		name  string
		build func(h *history) []lintkit.Finding
	}{
		{name: "an empty range", build: func(*history) []lintkit.Finding { return nil }},
		{name: "no baseline change", build: func(h *history) []lintkit.Finding {
			writeFile(h.t, filepath.Join(h.root, "notes.md"), "notes\n")
			h.commit("docs: add notes")
			return nil
		}},
		{name: "a count that falls", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 2", "go a 3")
			h.commit("test: cover more")
			return nil
		}},
		{name: "a rise with its trailer", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: drop the retry path\n\n" + trailerA)
			return nil
		}},
		{name: "two rises, two trailers, one beside Co-Authored-By", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 5", "go a 6")
			h.commit("refactor: two\n\nBody.\n\n" + trailerA + "\nCoverage-Drop: lib - kcov lost a file, " + reasonSentinel +
				"\nCo-Authored-By: Marker <marker@example.invalid>")
			return nil
		}},
		{name: "a lower-case, folded trailer", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\ncoverage-drop: a -\n  folded " + reasonSentinel)
			return nil
		}},
		{name: "a rise with no trailer", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: drop the retry path")
			return []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, false)}
		}},
		{name: "a trailer with no reason", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\nCoverage-Drop: a -")
			return []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, true)}
		}},
		{name: "a trailer naming another unit", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\nCoverage-Drop: lib - wrong unit " + reasonSentinel)
			return []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, false)}
		}},
		{name: "a trailer on a later commit than the rise", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x")
			sha := h.short("HEAD")
			h.commit("docs: explain\n\n" + trailerA)
			return []lintkit.Finding{raise(sha, "go", "a", 4, 6, false)}
		}},
		{name: "one of two rises justified", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 4", "go a 6")
			h.commit("refactor: two\n\n" + trailerA)
			return []lintkit.Finding{raise(h.short("HEAD"), "cobertura", "lib", 3, 4, false)}
		}},
		{name: "a trailer glued to the body paragraph", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\nThe retry path is gone.\n" + trailerA)
			return []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, false)}
		}},
		{name: "a trailer in its own paragraph above Co-Authored-By", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\n" + trailerA + "\n\nCo-Authored-By: Marker <marker@example.invalid>")
			return []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, false)}
		}},
		{name: "a unit added with uncovered code rises from 0", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura .ci 2", "cobertura lib 3", "go a 4")
			h.commit("feat: add ci scripts")
			return []lintkit.Finding{raise(h.short("HEAD"), "cobertura", ".ci", 0, 2, false)}
		}},
		{name: "a unit added fully covered", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura .ci 0", "cobertura lib 3", "go a 4")
			h.commit("feat: add ci scripts")
			return nil
		}},
		{name: "a unit removed", build: func(h *history) []lintkit.Finding {
			h.setBaseline("cobertura lib 3", "go a 4", "go old 2")
			h.commit("feat: add old\n\nCoverage-Drop: old - " + reasonSentinel)
			h.base = h.head()
			h.setBaseline("cobertura lib 3", "go a 4")
			h.commit("refactor: drop old")
			return nil
		}},
		{name: "a merge carrying a justified branch rise is skipped", build: func(h *history) []lintkit.Finding {
			gitOut(h.t, h.root, "switch", "--quiet", "--create", "topic")
			h.setBaseline("cobertura lib 3", "go a 6")
			h.commit("refactor: x\n\n" + trailerA)
			gitOut(h.t, h.root, "switch", "--quiet", "main")
			gitOut(h.t, h.root, "-c", "user.name=Marker", "-c", "user.email=marker@example.invalid",
				"merge", "--quiet", "--no-ff", "--no-edit", "topic")
			return nil
		}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			h := newHistory(t, startBaseline)
			want := tc.build(h)
			got, err := h.check()
			if err != nil {
				t.Fatalf("Check error = %v", err)
			}
			diffFindings(t, want, got)
		})
	}
}

