func TestCheck_historyFromTheRootCommit(t *testing.T) {
	t.Parallel()
	h := newHistory(t, startBaseline)
	h.setBaseline("cobertura lib 3", "go a 6")
	h.commit("refactor: drop the retry path")
	// The root commit has no parent and so no earlier baseline to raise.
	got, err := check(t, h.root, section, "HEAD")
	if err != nil {
		t.Fatalf("Check error = %v", err)
	}
	diffFindings(t, []lintkit.Finding{raise(h.short("HEAD"), "go", "a", 4, 6, false)}, got)
}

func TestCheck_historyBaselineDeleted(t *testing.T) {
	t.Parallel()
	h := newHistory(t, baseline("cobertura lib 3", "go a 4"))
	gitOut(t, h.root, "rm", "--quiet", "--", ".coverage-baseline.txt")
	h.commit("ci: drop the baseline")
	got, err := h.check()
	if err != nil {
		t.Fatalf("Check error = %v", err)
	}
	// Only the tree check reports: with no baseline every unit is held to 0.
	diffFindings(t, []lintkit.Finding{
		{Path: "a", Message: "3 uncovered statements, baseline 0"},
		{Path: "lib", Message: "2 uncovered lines, baseline 0"},
	}, got)
}

