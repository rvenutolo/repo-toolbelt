// gitEnv isolates fixture git commands from the machine's git config.
var gitEnv = []string{"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1"}

// section names the fixture reports and the default baseline.
const section = `{"reports":[{"format":"go","path":"cov/go.out"},{"format":"cobertura","path":"cov/c.xml"}]}`

// Every trailer reason in these cases carries this word; a finding names
// units and counts, never the message's own text.
const reasonSentinel = "markerReasonSentinel"

func gitOut(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), "git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), gitEnv...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// writeReports writes a module whose reports count go a=3, go .=0 and
// cobertura lib=2 uncovered.
func writeReports(t *testing.T, root string) {
	t.Helper()
	writeFile(t, filepath.Join(root, "go.mod"), "module example.com/m\n\ngo 1.22\n")
	writeFile(t, filepath.Join(root, "cov", "go.out"), "mode: set\n"+
		"example.com/m/a/x.go:3.1,5.2 3 0\n"+
		"example.com/m/main.go:1.1,2.2 1 1\n")
	writeFile(t, filepath.Join(root, "cov", "c.xml"), `<coverage><sources><source>`+root+`</source></sources>`+
		`<packages><package name="p"><classes><class filename="lib/t.sh"><lines>`+
		`<line number="1" hits="0"/><line number="2" hits="0"/><line number="3" hits="5"/>`+
		`</lines></class></classes></package></packages></coverage>`)
}

func baseline(lines ...string) string {
	return "# Generated by toolbelt update-coverage-baseline. Do not edit.\n" + strings.Join(lines, "\n") + "\n"
}

func check(t *testing.T, root, sectionJSON, rangeSpec string) ([]lintkit.Finding, error) {
	t.Helper()
	return coveragedrop.Check(t.Context(), lintkit.Context{Root: root, Section: []byte(sectionJSON), Hook: "ci", Range: rangeSpec})
}

func diffFindings(t *testing.T, want, got []lintkit.Finding) {
	t.Helper()
	if diff := cmp.Diff(want, got, cmp.AllowUnexported(lintkit.Finding{})); diff != "" {
		t.Errorf("Check mismatch (-want +got):\n%s", diff)
	}
	for _, f := range got {
		if strings.Contains(f.Message, reasonSentinel) {
			t.Errorf("finding %q quotes a trailer's reason", f.Message)
		}
	}
}

func TestCheck_tree(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		baseline string // "" writes no baseline file
		want     []lintkit.Finding
	}{
		{name: "counts equal to the baseline", baseline: baseline("cobertura lib 2", "go . 0", "go a 3")},
		{name: "counts below the baseline", baseline: baseline("cobertura lib 9", "go . 1", "go a 5")},
		{
			name:     "a count above the baseline",
			baseline: baseline("cobertura lib 2", "go . 0", "go a 2"),
			want:     []lintkit.Finding{{Path: "a", Message: "3 uncovered statements, baseline 2"}},
		},
		{
			name:     "a unit missing from the baseline counts as 0",
			baseline: baseline("go . 0", "go a 3"),
			want:     []lintkit.Finding{{Path: "lib", Message: "2 uncovered lines, baseline 0"}},
		},
		{
			name:     "the same directory in another format is another unit",
			baseline: baseline("cobertura a 3", "go . 0", "go lib 2"),
			want: []lintkit.Finding{
				{Path: "a", Message: "3 uncovered statements, baseline 0"},
				{Path: "lib", Message: "2 uncovered lines, baseline 0"},
			},
		},
		{name: "a baseline unit with no code any more", baseline: baseline("cobertura lib 2", "go a 3", "go gone 4")},
		{
			name: "no baseline file",
			want: []lintkit.Finding{
				{Path: "a", Message: "3 uncovered statements, baseline 0"},
				{Path: "lib", Message: "2 uncovered lines, baseline 0"},
			},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeReports(t, root)
			if tc.baseline != "" {
				writeFile(t, filepath.Join(root, ".coverage-baseline.txt"), tc.baseline)
			}
			got, err := check(t, root, section, "")
			if err != nil {
				t.Fatalf("Check error = %v", err)
			}
			diffFindings(t, tc.want, got)
		})
	}
}

