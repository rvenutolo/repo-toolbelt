func TestCheck_historySetupFailures(t *testing.T) {
	t.Parallel()
	t.Run("a range that does not resolve", func(t *testing.T) {
		t.Parallel()
		h := newHistory(t, startBaseline)
		if got, err := check(t, h.root, section, "no-such-ref..HEAD"); err == nil {
			t.Errorf("Check = %+v, want an error", got)
		}
	})
	t.Run("a range that is an option", func(t *testing.T) {
		t.Parallel()
		h := newHistory(t, startBaseline)
		if got, err := check(t, h.root, section, "--all"); err == nil {
			t.Errorf("Check = %+v, want an error", got)
		}
	})
	t.Run("a malformed baseline in a judged commit's parent", func(t *testing.T) {
		t.Parallel()
		h := newHistory(t, startBaseline)
		writeFile(t, filepath.Join(h.root, ".coverage-baseline.txt"), "go a 8O\n")
		h.commit("chore: mangle")
		h.base = h.head()
		h.setBaseline("cobertura lib 3", "go a 4")
		h.commit("chore: fix")
		_, err := h.check()
		if err == nil || !strings.Contains(err.Error(), h.short("HEAD^")) {
			t.Errorf("Check error = %v, want one naming %s", err, h.short("HEAD^"))
		}
	})
}
