package coverage

import (
	"bufio"
	"cmp"
	"errors"
	"fmt"
	"io"
	"maps"
	"slices"
	"strconv"
	"strings"
)

// BaselineHeader is the first line of a baseline file.
const BaselineHeader = "# Generated by toolbelt update-coverage-baseline. Do not edit."

// Unit is one line of the baseline: a unit of a report format.
type Unit struct {
	// Format is the report format, go or cobertura.
	Format string
	// Name is the unit, a repo-relative directory or `.`.
	Name string
}

// Baseline is the uncovered-statement count each unit is held to.
type Baseline map[Unit]int

// ParseBaseline reads a baseline file: one `<format> <unit> <count>` line per
// unit, where the unit may hold spaces; blank lines and `#` comments are
// skipped. A malformed line is an error naming its line number.
func ParseBaseline(r io.Reader) (Baseline, error) {
	b := Baseline{}
	scanner := bufio.NewScanner(r)
	scanner.Buffer(nil, maxLineBytes)
	n := 0
	for scanner.Scan() {
		n++
		text := strings.TrimSuffix(scanner.Text(), "\r")
		if strings.TrimSpace(text) == "" || strings.HasPrefix(text, "#") {
			continue
		}
		unit, count, err := parseBaselineLine(text)
		if err != nil {
			return nil, fmt.Errorf("line %d: %w", n, err)
		}
		if _, dup := b[unit]; dup {
			return nil, fmt.Errorf("line %d: %s unit %s is listed twice", n, unit.Format, unit.Name)
		}
		b[unit] = count
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("line %d: %w", n+1, err)
	}
	return b, nil
}

func parseBaselineLine(text string) (Unit, int, error) {
	format, rest, ok := strings.Cut(text, " ")
	last := strings.LastIndexByte(rest, ' ')
	if !ok || last < 0 {
		return Unit{}, 0, errors.New("want <format> <unit> <count>")
	}
	name, countText := rest[:last], rest[last+1:]
	if format != FormatGo && format != FormatCobertura {
		return Unit{}, 0, fmt.Errorf("format %q is not go or cobertura", format)
	}
	if err := checkUnitName(name); err != nil {
		return Unit{}, 0, err
	}
	count, err := strconv.Atoi(countText)
	if err != nil || count < 0 {
		return Unit{}, 0, fmt.Errorf("count %q is not a non-negative number", countText)
	}
	return Unit{Format: format, Name: name}, count, nil
}

// checkUnitName rejects a unit name a baseline line cannot carry and read
// back unchanged.
func checkUnitName(name string) error {
	if name == "" || strings.TrimSpace(name) != name || strings.ContainsAny(name, "\r\n") {
		return fmt.Errorf("unit %q is empty, has edge spaces or a line break", name)
	}
	return nil
}

// Write writes the baseline: the header, then one line per unit, sorted by
// format then unit.
func (b Baseline) Write(w io.Writer) error {
	units := slices.SortedFunc(maps.Keys(b), func(x, y Unit) int {
		return cmp.Or(strings.Compare(x.Format, y.Format), strings.Compare(x.Name, y.Name))
	})
	for _, u := range units {
		if err := checkUnitName(u.Name); err != nil {
			return err
		}
	}
	bw := bufio.NewWriter(w)
	fmt.Fprintln(bw, BaselineHeader)
	for _, u := range units {
		fmt.Fprintf(bw, "%s %s %d\n", u.Format, u.Name, b[u])
	}
	return bw.Flush()
}
