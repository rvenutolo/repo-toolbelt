func TestBaseline_Write(t *testing.T) {
	t.Parallel()
	b := coverage.Baseline{
		{Format: "go", Name: "internal/x"}:      3,
		{Format: "cobertura", Name: "lib"}:      0,
		{Format: "go", Name: "."}:               1,
		{Format: "cobertura", Name: "my dir"}:   2,
		{Format: "cobertura", Name: ".ci"}:      7,
		{Format: "go", Name: "internal/x/deep"}: 5,
	}
	var buf bytes.Buffer
	if err := b.Write(&buf); err != nil {
		t.Fatalf("Write error = %v", err)
	}
	want := "# Generated by toolbelt update-coverage-baseline. Do not edit.\n" +
		"cobertura .ci 7\n" +
		"cobertura lib 0\n" +
		"cobertura my dir 2\n" +
		"go . 1\n" +
		"go internal/x 3\n" +
		"go internal/x/deep 5\n"
	if got := buf.String(); got != want {
		t.Errorf("Write wrote\n%s\nwant\n%s", got, want)
	}
	back, err := coverage.ParseBaseline(&buf)
	if err != nil {
		t.Fatalf("ParseBaseline error = %v", err)
	}
	if diff := cmp.Diff(b, back); diff != "" {
		t.Errorf("round trip mismatch (-want +got):\n%s", diff)
	}
}

func TestBaseline_WriteEmpty(t *testing.T) {
	t.Parallel()
	var buf bytes.Buffer
	if err := (coverage.Baseline{}).Write(&buf); err != nil {
		t.Fatalf("Write error = %v", err)
	}
	if got, want := buf.String(), "# Generated by toolbelt update-coverage-baseline. Do not edit.\n"; got != want {
		t.Errorf("Write wrote %q, want %q", got, want)
	}
}

func TestBaseline_WriteRejectsUnwritableUnits(t *testing.T) {
	t.Parallel()
	for _, name := range []string{"a\nb", "a\rb", "", " lead", "trail "} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			var buf bytes.Buffer
			err := coverage.Baseline{{Format: "go", Name: name}: 1}.Write(&buf)
			if err == nil {
				t.Errorf("Write of unit %q succeeded, want an error", name)
			}
		})
	}
}

var errBoom = errors.New("boom")

type failingWriter struct{}

func (failingWriter) Write([]byte) (int, error) { return 0, errBoom }

func TestBaseline_WriteError(t *testing.T) {
	t.Parallel()
	err := coverage.Baseline{{Format: "go", Name: "."}: 1}.Write(failingWriter{})
	if !errors.Is(err, errBoom) {
		t.Errorf("Write error = %v, want %v", err, errBoom)
	}
}

func TestParseBaseline(t *testing.T) {
	t.Parallel()
	in := "# a comment\n\ngo . 1\r\ncobertura lib 0\n   \n"
	got, err := coverage.ParseBaseline(strings.NewReader(in))
	if err != nil {
		t.Fatalf("ParseBaseline error = %v", err)
	}
	want := coverage.Baseline{{Format: "go", Name: "."}: 1, {Format: "cobertura", Name: "lib"}: 0}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("ParseBaseline mismatch (-want +got):\n%s", diff)
	}
}

func TestParseBaseline_malformed(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		in   string
		line string
	}{
		{name: "one field", in: "# h\ngo\n", line: "line 2"},
		{name: "two fields", in: "go 1\n", line: "line 1"},
		{name: "unknown format", in: "go . 1\nlcov . 1\n", line: "line 2"},
		{name: "count not a number", in: "go . many\n", line: "line 1"},
		{name: "negative count", in: "go . -1\n", line: "line 1"},
		{name: "a unit with an edge space", in: "go  x 1\n", line: "line 1"},
		{name: "a percentage", in: "go . 80.0%\n", line: "line 1"},
		{name: "a repeated unit", in: "go . 1\ncobertura . 1\ngo . 2\n", line: "line 3"},
		{name: "a line over the length limit", in: "go " + strings.Repeat("a", 2<<20) + " 1\n", line: "line 1"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := coverage.ParseBaseline(strings.NewReader(tc.in))
			if err == nil {
				t.Fatalf("ParseBaseline = %v, want an error", got)
			}
			if !strings.Contains(err.Error(), tc.line) {
				t.Errorf("error %q does not name %s", err, tc.line)
			}
		})
	}
}

func FuzzParseBaseline(f *testing.F) {
	f.Add("# Generated by toolbelt update-coverage-baseline. Do not edit.\ngo . 1\ncobertura lib 0\n")
	f.Add("go a b c 3\n")
	f.Add("go . -1\n")
	f.Fuzz(func(t *testing.T, in string) {
		b, err := coverage.ParseBaseline(strings.NewReader(in))
		if err != nil {
			if b != nil {
				t.Errorf("ParseBaseline returned %v with error %v", b, err)
			}
			return
		}
		var buf bytes.Buffer
		if err := b.Write(&buf); err != nil {
			return // a parsed unit Write cannot spell, such as one with edge spaces
		}
		back, err := coverage.ParseBaseline(&buf)
		if err != nil {
			t.Fatalf("reparse error = %v", err)
		}
		if diff := cmp.Diff(b, back); diff != "" {
			t.Errorf("round trip mismatch (-want +got):\n%s", diff)
		}
	})
}
